    ('القرارات الإدارية', 'حالات الفصل في المدرسة')
) as t(cname, tname)
join public.violation_categories c on c.name = t.cname
where not exists (
  select 1 from public.violation_types vt
  where vt.category_id = c.id and vt.name = t.tname
);

-- ---------- تحقق ----------
select vc.name as category, count(vt.id) as types
from public.violation_categories vc
left join public.violation_types vt on vt.category_id = vc.id
group by vc.name
order by types desc, vc.name;
