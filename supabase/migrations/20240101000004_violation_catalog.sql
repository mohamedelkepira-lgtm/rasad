-- 1) التصنيفات الثمانية
with new_cats(name) as (
  values
    ('الانتظام والحضور'),
    ('السلوك العام'),
    ('الزي والنظافة الشخصية'),
    ('الالتزام داخل الحصة'),
    ('الممتلكات والبيئة المدرسية'),
    ('النزاهة الأكاديمية'),
    ('السلامة المهنية (Safety)'),
    ('القرارات الإدارية')
)
insert into public.violation_categories (name)
select nc.name
from new_cats nc
where not exists (
  select 1 from public.violation_categories vc where vc.name = nc.name
);

