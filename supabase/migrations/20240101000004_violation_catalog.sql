    ('السلوك العام', 'المشاجرات مع وقوع ضرر'),
    ('السلوك العام', 'التنمر'),
    ('السلوك العام', 'التحرش'),
    ('السلوك العام', 'السرقة'),
    -- الزي والنظافة الشخصية (3)
    ('الزي والنظافة الشخصية', 'عدم تهذيب الشعر'),
