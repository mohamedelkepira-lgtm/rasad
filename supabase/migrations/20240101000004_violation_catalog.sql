    -- الانتظام والحضور (5)
    ('الانتظام والحضور', 'الهروب من المدرسة'),
    ('الانتظام والحضور', 'الانضباط'),
    ('الانتظام والحضور', 'التأخير المتكرر'),
    ('الانتظام والحضور', 'الغياب'),
